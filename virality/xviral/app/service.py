class EmbeddingUnavailable(RuntimeError):
    """The text embedding provider did not answer and no fallback model set is configured: nothing could be scored."""


class EmbeddingNotAllowed(ValueError):
    """The request does not allow sending its text to the embedding provider and no local fallback model set is configured."""
MIN_HISTORY = 10          # fewer past posts than this and the account is treated as new: wider ranges, no own-record facts
REPORT_VERSION = 2
CORPUS = "our corpus of public posts"


def _ms(v) -> int | None:
    if v is None or v == "":
        return None
    if isinstance(v, (int, float)):
        return int(v if v > 1e11 else v * 1000)
    try:
        d = datetime.fromisoformat(str(v).strip().replace("Z", "+00:00"))
    except ValueError as e:
        raise ValueError(f"'{v}' is not a date and time we can read; use a form like 2026-11-18T16:00:00Z") from e
    return int((d if d.tzinfo else d.replace(tzinfo=timezone.utc)).timestamp() * 1000)


def _iso(ms: int, timespec: str = "seconds") -> str:
    return datetime.fromtimestamp(ms / 1000, timezone.utc).isoformat(timespec=timespec).replace("+00:00", "Z")


def _range(a: float, b: float, d: int = 1) -> str:
    return f"{a:.{d}f} to {b:.{d}f}"


def _versions_phrase(vs: list[int]) -> str:
    names = [str(v) for v in vs]
    return ("Version " + names[0]) if len(names) == 1 else "Versions " + ", ".join(names[:-1]) + " and " + names[-1]


def history_frame(handle: str, followers: int | None, past: list[dict], now_ms: int) -> pl.DataFrame:
    """Past posts typed in or uploaded by the user, as rows of the post schema."""
    rows = []
    for i, p in enumerate(past):
        ms = _ms(p.get("posted_at"))
        if ms is None or not (p.get("text") or "").strip():
            continue
        media = [dict(VIDEO)] if p.get("video") else [dict(advise.PHOTO)] if p.get("image") else []
        rows.append({"post_id": -stable_hash64("past", handle, ms, i), "author_id": -1, "author_handle": handle, "created_at_ms": ms, "created_at_src_ms": ms,
                     "snapshot_at_ms": now_ms, "snapshot_kind": "exact", "text": p["text"], "kind": "original", "is_reply": False, "media": media, "urls": [],
                     "likes": p.get("likes"), "replies": p.get("replies"), "reposts": p.get("reposts"), "views": p.get("views"),
                     "views_state": "count" if p.get("views") is not None else "absent", "author_followers": followers, "source": "analytics", "synthetic_id": True})
    empty = conform(pl.DataFrame()).clear()
    if not rows:
        return empty
    return conform(pl.DataFrame(rows, infer_schema_length=None, schema_overrides={"media": empty.schema["media"], "urls": empty.schema["urls"]})).sort("created_at_ms")


class Service:
    def __init__(self, scorer, scales: dict, posts: str | Path | None = None, evidence: dict | None = None, max_history: int = 300,
                 fast: bool = True, account_cache: int = 256, judge=None, judge_rule=None, judge_deadline: float = 40.0,
                 selective="auto", fallback: "Service | None" = None, forecast_validation: str | None = None, model_set: str | None = None):
        """judge: xviral.judge.Judge (or None): the second opinion on version comparisons. Posts supplied with a request
        (typed in or read from an X analytics export) are sent to it only when the request says so (`share_past_posts`).
        selective: a xviral.selective.SelectiveRule for these checkpoints, None for none, "auto" for the shipped file's default
        (fitted for the three bge-small models; do not use it with another model set).
        fallback: a Service on a model set with a local encoder. It answers a request when this set's embedding provider
        fails, or when the request does not allow its text to be sent to that provider; the report then says so.
        forecast_validation: the sentence stating what was measured for this model set's version comparisons."""
        self.scorer, self.posts, self.max_history = scorer, posts, max_history
        self.scorer.fast = fast
        self.fallback, self.model_set = fallback, model_set
        if forecast_validation:
            self.FORECAST_VALIDATION = forecast_validation
        # Per-kind confidence scales (launch pairs need their own; research/tracks/selective/REPORT.md). Ensembles only.
        rule = None if isinstance(selective, str) else selective
        if selective == "auto" and hasattr(scorer.model, "models") and len(scorer.model.models) > 1 and Path(advise.EVIDENCE_PATH).with_name("selective_rule.json").exists():
            from xviral.selective import SelectiveRule

            rule = SelectiveRule.load()
        self.advisor = advise.Advisor(scorer, scales, evidence=evidence, selective=rule, judge=judge, judge_rule=judge_rule, judge_deadline=judge_deadline)
        self.evidence = self.advisor.evidence
        self.rewriter = None                                        # xviral.rewrite.OpenAIRewriter, set by load() when configured
        data = Path(advise.EVIDENCE_PATH).parent
        self.launch_evidence = json.loads((data / "launch_evidence.json").read_text()) if (data / "launch_evidence.json").exists() else {}
        mp = data / "marketing_evidence.json"                       # further launch effects, same method (research/tracks/marketing)
        if self.launch_evidence and mp.exists():
            self.launch_evidence = {**{k: v for k, v in json.loads(mp.read_text()).items() if not k.startswith("_")}, **self.launch_evidence}
        self.launch_by_size = json.loads((data / "launch_by_size.json").read_text()) if (data / "launch_by_size.json").exists() else {}
        self._accounts: OrderedDict[str, dict] = OrderedDict()      # handle -> {history, followers, record, stamp}
        self._account_cache = account_cache
        self._accounts_lock = threading.Lock()

    # --- inputs --------------------------------------------------------------------------------------------

    def _corpus_account(self, handle: str) -> dict | None:
        """An account's posts from the corpus, kept across requests (scanning the corpus file is the slow part)."""
        if not (self.posts and handle):
            return None
        key, stamp = handle.lower(), os.path.getmtime(self.posts)
        with self._accounts_lock:
            hit = self._accounts.get(key)
            if hit is not None and hit["stamp"] == stamp:
                self._accounts.move_to_end(key)
                return hit if hit["history"] is not None else None
        h = pl.scan_parquet(self.posts).filter(pl.col("author_handle").str.to_lowercase() == key).collect().sort("created_at_ms").tail(self.max_history)
        entry = {"history": None, "followers": None, "record": None, "stamp": stamp}
        if h.height:
            known = h["author_followers"].drop_nulls()
            entry.update(history=h, followers=int(known[-1]) if known.len() else None)
        with self._accounts_lock:
            self._accounts[key] = entry
            while len(self._accounts) > self._account_cache:
                self._accounts.popitem(last=False)
        return entry if h.height else None

    def _history(self, handle: str, followers: int | None, past: list[dict], now_ms: int) -> tuple[pl.DataFrame, str, int | None]:
        if past:
            return history_frame(handle, followers, past, now_ms), "posts you supplied", followers
        acct = self._corpus_account(handle)
        if acct is not None:
            return acct["history"], CORPUS, followers or acct["followers"]
        return conform(pl.DataFrame()).clear(), "none", followers

    def _record(self, handle: str, history: pl.DataFrame, source: str) -> list[dict]:
        """Facts from the account's own posts; for a corpus account they are computed once and kept with the history."""
        acct = self._accounts.get(handle.lower()) if source == CORPUS else None
        if acct is None or acct["history"] is not history:
            return advise.own_record(history)
        if acct["record"] is None:
            acct["record"] = advise.own_record(history)
        return acct["record"]

    def account(self, handle: str, warm: bool = True) -> dict:
        """What we hold for a handle. With `warm`, the texts the model will read are embedded now, so the first report
        for the account does not wait for the encoder (the page calls this when the handle field loses focus)."""
        handle = (handle or "").lstrip("@").strip()
        acct = self._corpus_account(handle)
        if acct is None:
            return {"handle": handle or None, "known": False, "history_posts": 0, "followers": None}
        h = acct["history"]
        if warm and self.scorer.meta.get("emb_dim"):
            from xviral.model import features

            n = self.scorer.model.cfg.max_history
            tail = h if h.height <= n else h.filter(pl.col("created_at_ms") >= int(h["created_at_ms"].sort()[-n]))
            try:
                self.scorer.embed_fn(features.render_texts(conform(tail)), scope=handle)
            except EmbeddingError:      # warming is best effort: the first report embeds what is missing, or falls back
                pass
        return {"handle": handle, "known": True, "history_posts": h.height, "followers": acct["followers"], "last_post_at": _iso(int(h["created_at_ms"].max()))}

    @staticmethod
    def import_analytics(data: bytes, handle: str | None = None, limit: int = 500) -> dict:
        """An X analytics export (the per-post CSV) as `past_posts` for a request. Nothing is kept on the server."""
        from xviral.sources import analytics

        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "export.csv"
            path.write_bytes(data)
            try:
                df = analytics.read_export(path, handle=(handle or "").lstrip("@").strip() or None)
            except ValueError as e:
                raise ValueError("This file is not an X analytics export we recognise: it needs a post ID or post link column and an impressions column.") from e
            except Exception as e:      # noqa: BLE001  not a CSV at all
                raise ValueError("The file could not be read as a CSV.") from e
        rows = df.height
        df = df.filter(pl.col("text").fill_null("").str.strip_chars().str.len_chars() > 0)
        no_text = rows - df.height
        replies = df.filter(pl.col("kind") == "reply").height
        df = df.filter(pl.col("kind") != "reply").sort("created_at_ms")
        older = max(df.height - limit, 0)
        df = df.tail(limit)
        posts = [{"text": r["text"], "posted_at": _iso(r["created_at_ms"]), "likes": r["likes"], "views": r["views"], "replies": r["replies"], "reposts": r["reposts"]}
                 for r in df.select("text", "created_at_ms", "likes", "views", "replies", "reposts").iter_rows(named=True)]
        handles = [h for h in df["author_handle"].drop_nulls().unique().to_list() if h]
        return {"past_posts": posts, "summary": {"rows": rows, "posts": len(posts), "skipped_replies": replies, "skipped_without_text": no_text, "skipped_older": older,
                                                 "from": posts[0]["posted_at"] if posts else None, "to": posts[-1]["posted_at"] if posts else None,
                                                 "handle": handles[0] if len(handles) == 1 else None}}

    @staticmethod
    def _draft(v: dict) -> dict:
        m = v.get("media_info") or {}
        video, image = v.get("video") or m.get("kind") == "video", v.get("image") or m.get("kind") == "image"
        d = {"text": (v.get("text") or "").strip(), "media": [dict(VIDEO)] if video else [dict(advise.PHOTO)] if image else []}
        if d["media"] and m:            # an uploaded file: its measured size and length go where X's code and the features read them
            d["media"][0].update(width=m.get("width"), height=m.get("height"),
                                 duration_ms=int(1000 * m["duration_s"]) if video and m.get("duration_s") else None)
        # The seam for media understanding (xviral/app/media.py): carried to the scorer, which ignores both keys today.
        if v.get("media_attributes"):
            d["media_attributes"] = v["media_attributes"]
        if v.get("media_embedding") is not None:
            d["media_embedding"] = v["media_embedding"]
        return d

    # --- the measured checklist -----------------------------------------------------------------------------

    def _generic_checklist(self, draft: dict) -> list[dict]:
        ev, text = self.evidence, draft["text"]
        items = []

        def add(key: str, ok: bool, yes: str, no: str, evidence_key: str):
            e = ev.get(evidence_key) or {}
            if not e.get("supported"):
                return
            items.append({"key": key, "ok": bool(ok), "text": yes if ok else no, "grade": None,
                          "measured": f"In {e['pairs']:,} pairs of posts by the same account on the same topic, the version with this did better {100 * e['win_rate']:.0f}% of the time "
                                      f"({100 * e['lo']:.0f} to {100 * e['hi']:.0f}%)."})
        lines = [ln for ln in text.split("\n") if ln.strip()]
        add("media", bool(draft["media"]), "Has an image or video.", "No image or video attached.", "media")
        add("lines", len(lines) >= 3, "Broken into three or more lines.", "One block of text; fewer than three lines.", "lines")
        if "http" in text:
            add("link", "http" not in (lines[0] if lines else ""), "The link is not in the first line.", "The link is in the first line.", "link_not_first")
        return items

    @staticmethod
    def _launch_measured(e: dict, what: str = "the one with this", pooled: bool = False) -> str:
        r = e.get("likes_ratio") or {}
        return (f"Among launch posts by the same account{' (every account in the corpus pooled)' if pooled else ''}, {what} did better {100 * e['win_rate']:.0f}% of the time "
                f"({100 * e['lo']:.0f} to {100 * e['hi']:.0f}%), {e['pairs']:,} pairs from {e['accounts']} accounts"
                + (f"; about {r['ratio']:.1f}x the likes ({_range(r['lo'], r['hi'])})." if r.get("ratio") else "."))

    @staticmethod
    def _numbers(e: dict) -> dict:
        r, a = e.get("likes_ratio") or {}, e.get("adjusted_likes_ratio") or {}
        return {"win_rate": e["win_rate"], "win_lo": e["lo"], "win_hi": e["hi"], "pairs": e["pairs"], "accounts": e["accounts"],
                "likes_ratio": r.get("ratio"), "likes_ratio_lo": r.get("lo"), "likes_ratio_hi": r.get("hi"),
                "adjusted_likes_ratio": a.get("ratio"), "adjusted_lo": a.get("lo"), "adjusted_hi": a.get("hi")}

    def _launch_checklist(self, draft: dict, ctx: dict | None = None) -> list[dict]:
        """For launch posts: the traits that separate an account's stronger launch posts from its weaker ones."""
        ev, tr = self.launch_evidence, post_type.traits(draft["text"], draft["media"])
        items = []

        def add(key: str, ok: bool, yes: str, no: str, evidence_key: str, note: str = ""):
            e = ev.get(evidence_key) or {}
            if not e.get("grade"):
                return
            items.append({"key": key, "ok": bool(ok), "text": yes if ok else no, "grade": e["grade"], "measured": self._launch_measured(e) + (" " + note if note else "")})
        add("names_product", tr["names_product_first_line"], "The first line names the product.", "The first line does not name the product.", "names_product_first_line")
        add("lines", tr["lines3"], "Laid out on three or more lines.", "Fewer than three lines.", "lines3")
        if tr["video"]:
            add("video", True, "Has a video or GIF.", "", "video_vs_none")
        elif tr["image"]:
            add("video", False, "", "Has an image, not a video or GIF.", "video_vs_image", "A still image is not established as better than no media for a launch post.")
        else:
            add("video", False, "", "No video or GIF.", "video_vs_none", "A still image is not established as better than no media for a launch post.")
        add("announcement_first", not tr["open_problem"], "Opens with the announcement.", "Opens with a problem statement or a question, not the announcement.", "announcement_not_problem_first")
        add("no_link", not tr["ext_link"], "No external link in the post.", "Has an external link in the post.", "no_link_in_post",
            "Whether a link in a reply recovers the clicks could not be measured.")
        add("number", tr["open_number"], "The first line contains a number.", "No number in the first line.", "open_number", "The weakest of the findings.")
        if ctx and ctx.get("hours_since_previous") is not None:
            add("quiet_day", ctx["hours_since_previous"] >= 24, "Nothing posted in the 24 hours before.", f"Your previous post is {ctx['hours_since_previous']:.0f} hours before this one; under 24.", "quiet_prev24h")
            add("only_launch_this_week", not ctx.get("launch_in_previous_week"), "No other launch post in the previous 7 days.", "Another launch-type post went out in the previous 7 days.",
                "no_launch_in_previous_week", "This one weakened after April 2026.")
        order = {"A": 0, "A-": 1, "B": 2, "B-": 3, "C": 4}
        return sorted(items, key=lambda i: (i["ok"], order.get(i["grade"], 9)))

    def checklist(self, draft: dict, kind: str, ctx: dict | None = None) -> list[dict]:
        return self._launch_checklist(draft, ctx) if kind == "launch" and self.launch_evidence else self._generic_checklist(draft)

    @staticmethod
    def _timing_context(history: pl.DataFrame, when_ms: int) -> dict:
        """What the account posted shortly before the planned time: inputs of the timing lines of the launch checklist."""
        if not history.height:
            return {}
        h = history.filter(pl.col("created_at_ms") < when_ms)
        if not h.height:
            return {}
        week = h.filter(pl.col("created_at_ms") >= when_ms - 7 * 86_400_000)
        return {"hours_since_previous": (when_ms - int(h["created_at_ms"].max())) / 3_600_000,
                "launch_in_previous_week": any(post_type.classify(t)["type"] == "launch" for t in week["text"].to_list())}

    def type_expectation(self, kind: str) -> dict | None:
        """How posts of this kind do against the account's own usual, for company and founder accounts."""
        e = ((self.launch_evidence.get("_types") or {}).get("company_and_founder") or {}).get(kind, {}).get("likes")
        if not e or e["posts"] < 50:
            return None
        return {"likes_vs_usual": e["geo_mean_ratio"], "lo": e["geo_mean_lo"], "hi": e["geo_mean_hi"], "beat_usual": e["beat_own_median"], "own_top_10pct": e.get("top10_of_own"),
                "posts": e["posts"], "accounts": e["accounts"],
                "statement": f"{post_type.LABELS[kind]} posts by company and founder accounts got {e['geo_mean_ratio']:.1f}x the account's usual likes ({e['geo_mean_lo']:.1f} to {e['geo_mean_hi']:.1f}); "
                             f"{100 * e['beat_own_median']:.0f}% beat the account's usual. Measured on {e['posts']:,} posts from {e['accounts']} accounts. "
                             + ("The forecast above includes part of this lift; it still tends to come in low for this kind of post."
                                if getattr(self.scorer, "type_correction", None) else "The forecast above does not yet include this lift.")}

    # --- the launch-day plan ---------------------------------------------------------------------------------

    def launch_plan(self, drafts: list[dict], hours_since_previous: float | None) -> dict | None:
        """The measured launch traits, checked against every version. Built only from launch_evidence.json: a trait
        whose evidence carries no grade is left out, never filled in."""
        ev = self.launch_evidence
        if not ev:
            return None
        traits = [post_type.traits(d["text"], d["media"]) for d in drafts]
        items = []

        def add(key: str, rule: str, evidence_key: str, met: list, measured: str | None = None, notes: tuple = (), sub: str | None = None,
                on_draft: bool = True):
            e = ev.get(evidence_key) or {}
            if not e.get("grade"):
                return
            src = e[sub] if sub else e
            items.append({"key": key, "rule": rule, "grade": e["grade"], "met": met, "measured": measured or self._launch_measured(src, pooled=bool(sub)),
                          "notes": [n for n in notes if n], "numbers": self._numbers(src), "depends_on_draft": on_draft})

        add("names_product", "The first line names the product", "names_product_first_line", [t["names_product_first_line"] for t in traits])
        add("lines", "Three or more lines", "lines3", [t["lines3"] for t in traits])
        vn, vi = ev.get("video_vs_none") or {}, ev.get("video_vs_image") or {}
        if vn.get("grade") and vi.get("grade"):
            add("video", "A video or GIF", "video_vs_none", [t["video"] for t in traits],
                measured=self._launch_measured(vn, "the one with a video or GIF, against one with no media,") + " "
                + self._launch_measured(vi, "the one with a video or GIF, against one with an image,"),
                notes=("A still image is not established as better than no media for a launch post.",))
            items[-1]["numbers"] = {"against_no_media": self._numbers(vn), "against_image": self._numbers(vi)}
        add("announcement_first", "Opens with the announcement, not a problem statement or a question", "announcement_not_problem_first", [not t["open_problem"] for t in traits])
        add("original_post", "An original post, not a quote post", "original_not_quote", [True] * len(drafts), notes=("Every version here is scored as an original post.",),
            on_draft=False)
        add("no_link", "No external link in the post", "no_link_in_post", [not t["ext_link"] for t in traits], notes=("Whether a link in a reply recovers the clicks could not be measured.",))
        sp = ev.get("spacing") or {}
        gap_ok = None if hours_since_previous is None else hours_since_previous >= 2
        when_note = ("No posting time was given, so the gap to your previous post is not checked." if hours_since_previous is None
                     else f"The posting time given is {hours_since_previous:.1f} hours after your previous post.")
        close = (f"Launch posts less than 2 hours after the account's previous post got {sp['ratio_when_closer']:.2f}x the likes of the same account's other launch posts "
                 f"({_range(sp['ratio_lo'], sp['ratio_hi'], 2)}); {sp['posts_closer']} such posts, {sp['accounts']} accounts." if sp.get("supported") else "")
        two = ev.get("two_hours_after_previous") or {}
        add("two_hours", "At least 2 hours after your previous post", "two_hours_after_previous", [gap_ok] * len(drafts), notes=(close, when_note),
            sub="all_accounts" if two.get("all_accounts") else None, on_draft=False)
        if items and items[-1]["key"] == "two_hours":
            items[-1]["measured"] = items[-1]["measured"].replace("the one with this", "the one posted at least 2 hours after the previous post")
        order = {"A": 0, "A-": 1, "B": 2, "B-": 3, "C": 4}
        items.sort(key=lambda i: order.get(i["grade"], 9))          # stable: strongest evidence first, then the order above
        own = [i for i in items if i["depends_on_draft"]]
        met = [sum(bool(i["met"][v]) for i in own) for v in range(len(drafts))]
        return {"items": items, "checks_on_the_text": len(own), "met_by_version": met,
                "grades": {"A": "passes the rule fixed in advance and is confirmed separately before and after 23 April 2026",
                           "A-": "passes in the main set of launch posts and in both periods; weaker in the strict set",
                           "B": "passes the rule; in one of the two periods the sample is too small to confirm it on its own",
                           "C": "holds only when the launch posts of every account in the corpus are pooled"},
                "basis": "Every line is measured inside accounts, on launch posts of company and founder accounts, on likes. These are associations, not experiments."}

    def size_benchmark(self, followers: int, usual_likes: float | None) -> dict | None:
        """What launch posts did for accounts in this follower range (xviral/data/launch_by_size.json)."""
        tiers = self.launch_by_size.get("tiers") or []
        tier = next((t for t in tiers if followers >= t["followers_from"] and (t["followers_below"] is None or followers < t["followers_below"])), None)
        if tier is None:
            return None
        lo, hi = tier["followers_from"], tier["followers_below"]
        label = f"under {hi:,}" if lo == 0 else f"{lo:,} or more" if hi is None else f"{lo:,} to {hi:,}"
        if tier.get("too_thin"):
            return {"tier": tier["tier"], "label": label, "too_thin": True, "posts": tier["posts"], "accounts": tier["accounts"],
                    "statement": f"Accounts with {label} followers: {tier['posts']} launch posts from {tier['accounts']} accounts in the data, too few to state what is typical."}
        out = {k: tier[k] for k in ("tier", "likes_vs_usual", "lo", "hi", "beat_usual", "own_top_10pct", "likes_median", "likes_p25", "likes_p75", "posts", "accounts")}
        out["label"] = label
        out["statement"] = (f"Launch posts by company and founder accounts with {label} followers got {tier['likes_vs_usual']:.1f}x the account's usual likes ({_range(tier['lo'], tier['hi'])}); "
                            f"{100 * tier['beat_usual']:.0f}% beat the account's usual and {100 * tier['own_top_10pct']:.0f}% landed in its own top 10%. "
                            f"The typical such post got {tier['likes_median']:,.0f} likes (middle half {tier['likes_p25']:,.0f} to {tier['likes_p75']:,.0f}). "
                            f"Measured on {tier['posts']:,} posts from {tier['accounts']} accounts.")
        if usual_likes:
            out["applied_to_your_usual"] = {"likes": usual_likes * tier["likes_vs_usual"], "lo": usual_likes * tier["lo"], "hi": usual_likes * tier["hi"]}
            out["statement"] += (f" Your usual {usual_likes:,.0f} likes times that lift is {usual_likes * tier['likes_vs_usual']:,.0f} "
                                 f"({usual_likes * tier['lo']:,.0f} to {usual_likes * tier['hi']:,.0f}). The forecast does not include this lift.")
        return out

    # --- versions against each other -------------------------------------------------------------------------

    def compare_versions(self, reports: list[dict], judged: dict | None = None) -> dict:
        """Every version against every other, each pair judged by the gates of any comparison (calibrated probability at
        or above the threshold, every model agreeing). A winner is named only when it clears the gates against every
        other version; otherwise the versions no other version beats are named as too close to call.
        judged: {(i, j): the judge's result for (version j+1, version i+1)}, i < j. A pair with a result is decided by the
        forecasting model and the language model together (the fitted rule replaces the every-model-agrees gate) and says
        which of the two opinions preferred which version; a pair without one is decided as before."""
        n = len(reports)
        outcome = self.advisor._target()
        if n == 1:
            return {"status": "one_version", "winner": None, "confidence": None, "statement": None, "contenders": [1], "eliminated": [], "pairs": [], "outcome": outcome}
        pairs, cmp = [], {}
        beats = [[False] * n for _ in range(n)]          # beats[i][j]: version j+1 is predicted, with confidence, to do better than version i+1
        for i in range(n):
            for j in range(i + 1, n):
                c = self.advisor.compare(reports[i], reports[j], (judged or {}).get((i, j)))
                cmp[(i, j)] = c
                beats[i][j] = c["status"].startswith("recommended")
                beats[j][i] = c["status"] == "predicted_worse" and (c["members_agree"] is not False or "opinions" in c)
                pairs.append({"a": i + 1, "b": j + 1, "p_b_better": c["p_better"], "predicted_ratio_b_over_a": c["predicted_ratio"],
                              "members_agree": c["members_agree"], "status": c["status"], "decided_by_members": c.get("decided_by_members") or "forecast",
                              **self._opinions(c, i + 1, j + 1)})

        def p_of(w, i):          # P(version w+1 does better than version i+1)
            return cmp[(i, w)]["p_better"] if i < w else 1 - cmp[(w, i)]["p_better"]

        def ratio_of(w, i):
            return cmp[(i, w)]["predicted_ratio"] if i < w else 1 / cmp[(w, i)]["predicted_ratio"]
        contenders = [j for j in range(n) if not any(beats[j][k] for k in range(n) if k != j)]
        eliminated = [j for j in range(n) if j not in contenders]
        winner = next((j for j in range(n) if all(beats[i][j] for i in range(n) if i != j)), None)
        base = {"contenders": [c + 1 for c in contenders], "eliminated": [e + 1 for e in eliminated], "pairs": pairs, "outcome": outcome}
        both = [p for p in pairs if p.get("opinions")]
        if both:
            ag = [p for p in both if p["opinions"]["agree"]]
            base["opinions"] = {"pairs_with_both": len(both), "pairs_agreeing": len(ag),
                                "statement": (f"The forecasting model and the language model were both asked about {len(both)} of {len(pairs)} pair{'s' if len(pairs) != 1 else ''}; "
                                              f"they preferred the same version in {len(ag)}."
                                              + ("" if len(both) == len(pairs) else " The other pairs were decided by the forecasting model alone."))}
        if winner is not None:
            others = [i for i in range(n) if i != winner]
            conf = min(p_of(winner, i) for i in others)
            nxt = min(others, key=lambda i: ratio_of(winner, i))
            # The ratio is the forecasting model's. When the language model carried a verdict the forecasting model did not
            # share, that ratio is below 1 and would contradict the sentence, so it is left out (the pair table still has it).
            r = ratio_of(winner, nxt)
            if n == 2:
                st = f"Version {winner + 1} is predicted to do better than version {nxt + 1} ({100 * conf:.0f}% likely" + (f", about {r:.1f}x the {outcome})." if r >= 1 else ").")
            else:
                st = (f"Version {winner + 1} is predicted to do better than every other version ({100 * conf:.0f}% likely or more against each"
                      + (f"; about {r:.1f}x the {outcome} of version {nxt + 1}, the closest)." if r >= 1 else ")."))
            if both:
                mine = [p for p in both if winner + 1 in (p["a"], p["b"])]
                agree = [p for p in mine if p["opinions"]["agree"]]
                if mine:
                    st += (" The forecasting model and the language model both prefer it." if len(agree) == len(mine) and n == 2 else
                           " The forecasting model and the language model both prefer it against every other version." if len(agree) == len(mine) else
                           " The language model prefers it; the forecasting model alone does not." if n == 2 and mine[0]["opinions"]["language_model_prefers"] == winner + 1 else
                           " The forecasting model prefers it; the language model alone does not." if n == 2 else
                           f" The two models agree on {len(agree)} of its {len(mine)} comparisons.")
            return {"status": "clear_winner", "winner": winner + 1, "confidence": conf, "statement": st, **base}
        if eliminated and len(contenders) > 1:
            st = (f"Too close to call between {_versions_phrase([c + 1 for c in contenders]).lower()}. "
                  f"{_versions_phrase([e + 1 for e in eliminated])} {'is' if len(eliminated) == 1 else 'are each'} predicted to do worse than another version.")
        else:
            st = "The versions are too close to call. Post whichever you prefer; we cannot tell them apart with confidence."
        return {"status": "too_close", "winner": None, "confidence": None, "statement": st, **base}

    @staticmethod
    def _opinions(c: dict, a: int, b: int) -> dict:
        """Which version each of the two opinions preferred in the comparison of versions a and b (b is "this version")."""
        o = c.get("opinions")
        if not o:
            return {"decided_by": "forecasting model"} if c.get("p_better") is not None else {}
        ver = lambda who: None if o[who]["prefers"] == "neither" else b if o[who]["prefers"] == "this version" else a      # noqa: E731
        return {"decided_by": "forecasting model and language model", "kind": c.get("comparison_kind"), "p_b_better_forecast_model_only": c.get("p_forecast_model_only"),
                "opinions": {"forecast_model_prefers": ver("forecast_model"), "forecast_model_p_b_better": o["forecast_model"]["p_better"],
                             "language_model_prefers": ver("language_model"), "language_model_p_b_better": o["language_model"]["p_better"], "agree": bool(o["agree"])}}

    # --- the second opinion: what may be sent, and what the report says about it ---------------------------------

    def judge_plan(self, req: dict, source: str, n_versions: int, will_suggest: bool) -> dict:
        """Whether the judge runs for this request, and why not when it does not. Posts the caller supplied (typed in, or
        read from an X analytics export) never leave the server unless the request sets `share_past_posts`."""
        adv = self.advisor
        if adv.judge is None:
            return {"use": False, "why_not": "no language model is configured on this server"}
        if not adv.judge_ready():
            return {"use": False, "why_not": f"no fitted rule for the model {adv.judge.model}; the forecasting model decides alone"}
        if req.get("judge") is False:
            return {"use": False, "why_not": "the request opted out (judge: false)"}
        if adv._target() != "likes":
            return {"use": False, "why_not": "comparisons on this server use views, and the second opinion is fitted on likes only"}
        if n_versions < 2 and not will_suggest:
            return {"use": False, "why_not": "one version and no rewrites: there is nothing to compare"}
        if source == "posts you supplied" and not req.get("share_past_posts"):
            return {"use": False, "why_not": "the account's past posts came with the request (typed in or from an X analytics export) and the request does not allow "
                                             "sending them (share_past_posts: true); the forecasting model decides alone"}
        return {"use": True, "why_not": None}

    def _judge_block(self, plan: dict, source: str, summaries: list[dict], n_versions: int, wait_s: float) -> dict:
        """summaries: [the batch of version pairs or None, the batch of rewrites against the draft or absent]."""
        rewrites = summaries[1]["pairs"] if len(summaries) > 1 and summaries[1] else 0
        j = self.advisor.judge
        out = {"configured": j is not None, "used": False, "provider": None, "model": None, "why_not": plan["why_not"], "sent": None,
               "pairs": 0, "pairs_answered": 0, "calls": 0, "cost_usd": 0.0, "added_ms": 0, "error": None}
        if j is None:
            return out
        out.update(provider=j.provider, model=j.model)
        summaries = [s for s in summaries if s]
        if not plan["use"]:
            return out
        if not summaries:
            out["why_not"] = "there was nothing to compare: one version, and no proposed rewrite passed the checks"
            return out
        answered = sum(s["pairs_answered"] for s in summaries)
        sent_posts = max(s["history_posts_sent"] for s in summaries)
        out.update(used=answered > 0, pairs=sum(s["pairs"] for s in summaries), pairs_answered=answered, calls=sum(s["calls"] for s in summaries),
                   cost_usd=round(sum(s["usd"] for s in summaries), 6), added_ms=round(1000 * wait_s), error=next((s["error"] for s in summaries if s["error"]), None),
                   sent={"to": j.provider, "model": j.model, "versions": n_versions, "rewrites": rewrites,
                         "account_line": "handle and follower count", "past_posts": sent_posts,
                         "past_posts_source": None if not sent_posts else source, "past_posts_fields": "text, kind of media, link domain, like count" if sent_posts else None})
        if answered == 0:
            out["why_not"] = ("the language model did not answer in time" if out["error"] in (None, "deadline") else f"the language model's calls failed ({out['error']})") \
                + "; the forecasting model decided alone. The versions and posts listed under `sent` were sent all the same"
        return out

    def _judge_validation(self, kinds: set) -> str | None:
        """What was measured for the judge configuration that decided this report's comparisons: one statement per kind
        of pair that occurred (two launch posts; anything else), taken from the rule file, never written by hand here."""
        adv = self.advisor
        if not adv.judge_ready():
            return None
        out = [(adv.judge_rule.validated(adv.judge.model, k) or {}).get("statement") for k in ("launch", "same_topic") if k in kinds]
        return " ".join(x for x in out if x) or None

    # --- the report ------------------------------------------------------------------------------------------

    def suggestions(self, history: pl.DataFrame, draft: dict, account: dict, when: int, n: int, launch: bool, use_judge: bool = False,
                    share_history: bool = False) -> dict:
        """Rewrites proposed by a language model, screened for faithfulness, then judged like any other version.
        A rewrite is called better only when it clears the advisor's gates; the others are listed as not better."""
        from xviral import rewrite

        judge_summary = None
        proposals = self.rewriter.candidates(draft["text"], n=n, launch=launch)
        screened = rewrite.screen(draft["text"], proposals, self.scorer.embed_fn, self.advisor.min_meaning_cos)
        live = [s for s in screened if s["ok"]]
        rows = []
        if live:
            out = self.advisor.advise(history, draft, account, when, alternatives=[{"text": s["text"], "media": draft["media"], "label": f"Suggested {i + 1}"} for i, s in enumerate(live)],
                                      use_judge=use_judge, share_history=share_history)
            judge_summary = out.get("judge")
            by = {c["change"]: c for c in out["changes"] if c["operator"] is None}
            for i, s in enumerate(live):
                c = by[f"Suggested {i + 1}"]
                o = c.get("opinions")
                rows.append({"text": s["text"], "status": c["status"], "p_better": c["p_better"], "predicted_ratio": c["predicted_ratio"], "members_agree": c["members_agree"],
                             "likes_median": c["likes_q50"], "meaning_cos": s.get("meaning_cos"),
                             "decided_by": "forecasting model and language model" if o else "forecasting model", "kind": c.get("comparison_kind") if o else None,
                             "opinions": None if not o else {"forecast_model_prefers": "rewrite" if o["forecast_model"]["prefers"] == "this version" else "draft",
                                                             "language_model_prefers": "rewrite" if o["language_model"]["prefers"] == "this version" else "draft", "agree": bool(o["agree"])},
                             "checklist": self.checklist({"text": s["text"], "media": draft["media"]}, "launch" if launch else "")})
        rows.sort(key=lambda r: -(r["p_better"] or 0))
        return {"written_by": f"language model ({self.rewriter.model}); judged by the forecasting model"
                              + (" together with a second language model" if judge_summary and judge_summary["pairs_answered"] else ""),
                "_judge": judge_summary,
                "proposed": len(proposals), "dropped": [{"why": s["why"]} for s in screened if not s["ok"]],
                "better": [r for r in rows if r["status"].startswith("recommended")], "not_better": [r for r in rows if not r["status"].startswith("recommended")]}

    # --- the text embedding: who may see the text, what it cost, and what happens when the provider fails ---------

    def embedding_info(self) -> dict:
        enc, spec = getattr(self.scorer, "encoder", None), getattr(self.scorer, "encoder_spec", None) or {}
        external = enc is not None and not getattr(enc, "local", True)
        d = enc.describe() if enc is not None and hasattr(enc, "describe") else {}
        return {"encoder": spec.get("name"), "provider": d.get("provider") or ("local" if not external else None), "model": d.get("model") or spec.get("model"),
                "dimensions": spec.get("dimensions"), "external": external}

    def _embedding_refusal(self, req: dict) -> str | None:
        """Why this request's text may not go to the embedding provider, or None when it may (or when the encoder is local)."""
        if not self.embedding_info()["external"]:
            return None
        if req.get("external_embedding") is False:
            return "the request opted out of the embedding provider (external_embedding: false)"
        if (req.get("past_posts") or []) and not req.get("share_past_posts"):
            return ("the account's past posts came with the request (typed in or from an X analytics export) and the request does not allow "
                    "sending them to a provider (share_past_posts: true)")
        return None

    def _embedding_block(self, usage: dict | None, counts: dict | None, **extra) -> dict:
        info, usage, counts = self.embedding_info(), usage or {}, counts or {}
        sent = int(counts.get("sent", 0)) if info["external"] else 0
        return {**info, "texts": int(counts.get("texts", 0)), "texts_sent": sent, "texts_from_cache": int(counts.get("texts", 0)) - int(counts.get("sent", 0)),
                "calls": int(usage.get("calls", 0)), "tokens": int(usage.get("tokens", 0)), "cost_usd": round(float(usage.get("usd", 0.0)), 6),
                "ms": round(1000 * float(usage.get("seconds", 0.0))), "sent": {"to": info["provider"], "model": info["model"], "what": EMBED_SENT} if sent else None,
                "fallback_used": False, "fallback_reason": None, "primary_encoder": None, "error": None, **extra}

    def analyze(self, req: dict) -> dict:
        """The report. With an API encoder, text leaves the server only when the request allows it; when it may not, or when
        the provider fails, the fallback model set (local encoder) answers and the report's `embedding` block says so.
        Without a fallback the first case is refused (EmbeddingNotAllowed) and the second raises EmbeddingUnavailable:
        a request is never scored with missing or substitute vectors."""
        why = self._embedding_refusal(req)
        primary = self.embedding_info()
        if why is not None:
            if self.fallback is None:
                raise EmbeddingNotAllowed(f"this server scores posts with an embedding from {primary['provider']} ({primary['model']}): {why}. "
                                          "Set share_past_posts: true (and leave external_embedding on), or ask the operator to configure the local fallback models.")
            out = self.fallback.analyze(req)
            out["embedding"].update(fallback_used=True, fallback_reason=why, primary_encoder=primary["encoder"])
            return out
        enc = getattr(self.scorer, "encoder", None)
        if enc is not None and hasattr(enc, "take_usage"):
            enc.take_usage()
        self.scorer.embed_counts = {"texts": 0, "sent": 0}
        try:
            return self._analyze(req)
        except EmbeddingError as e:
            usage = enc.take_usage() if enc is not None and hasattr(enc, "take_usage") else {}
            if self.fallback is None:
                raise EmbeddingUnavailable(f"{e}. Nothing was scored. The texts of this request were sent to {primary['provider']} all the same.") from e
            out = self.fallback.analyze(req)
            out["embedding"].update(fallback_used=True, fallback_reason="the embedding provider failed", primary_encoder=primary["encoder"], error=str(e),
                                    primary_attempt={"to": primary["provider"], "model": primary["model"], "what": EMBED_SENT, "calls": int(usage.get("calls", 0)),
                                                     "note": "the texts were sent before the failure"})
            return out

    def _analyze(self, req: dict) -> dict:
        t0 = time.time()
        clock = time.perf_counter()
        self.scorer.timings = {}
        now_ms = int(t0 * 1000)
        handle = (req.get("handle") or "").lstrip("@").strip()
        versions = [v for v in (req.get("versions") or []) if (v.get("text") or "").strip()]
        if not versions:
            raise ValueError("at least one version of the draft is required")
        history, source, followers = self._history(handle, req.get("followers"), req.get("past_posts") or [], now_ms)
        if followers is None:
            raise ValueError("follower count is required for an account we have no posts for")
        t_hist = time.perf_counter() - clock
        asked_when = _ms(req.get("when"))
        last_ms = int(history["created_at_ms"].max()) if history.height else None
        when = asked_when or (max(now_ms, last_ms + 3_600_000) if history.height else now_ms)
        account = {"handle": handle or "draft", "followers": int(followers)}
        if not history.height:
            account["author_id"] = -1
        drafts = [self._draft(v) for v in versions]
        suggest = int(req.get("suggest") or 0)
        plan = self.judge_plan(req, source, len(drafts), bool(suggest and self.rewriter is not None))
        share = source == CORPUS or bool(req.get("share_past_posts"))
        # Every pair of versions goes to the judge in one batch, started now so that it runs while the forecasting model scores.
        order = [(i, j) for i in range(len(drafts)) for j in range(i + 1, len(drafts))]
        batch = self.advisor.start_judging(history, account, [(drafts[j], drafts[i]) for i, j in order], share, when) if plan["use"] else None
        out = self.advisor.advise(history, drafts[0], account, when, alternatives=[{**d, "label": f"Version {i + 2}"} for i, d in enumerate(drafts[1:])],
                                  record=self._record(handle, history, source), use_judge=False)
        t_scored = time.perf_counter()
        judged = dict(zip(order, batch.results())) if batch is not None else {}
        judge_wait = time.perf_counter() - t_scored
        if judged:           # version 1 against each other version: the same comparisons, with the second opinion
            base_rep = {"likes": out["draft"]["likes"], "views_24h": out["draft"]["views_24h"], "members": out["draft"].get("members") or [], "reads_as_launch": out["draft"].get("reads_as_launch"),
                        "kind_reports": out["draft"].get("kind_reports")}
            target = self.advisor._target()
            for c in out["changes"]:
                if c["operator"] is None and c["change"].startswith("Version "):
                    j = int(c["change"].split()[1]) - 1
                    if judged.get((0, j)) is not None:
                        cmp = self.advisor._compare(base_rep, c["report"], target, judged[(0, j)])
                        status, why = self.advisor._status(cmp, {"supported": True}, True)
                        c.update({**cmp, "status": status, "why": why})
        alts = {c["change"]: c for c in out["changes"] if c["operator"] is None}
        d = out["draft"]
        suggested, judge_summaries = None, [batch.summary() if batch is not None else None]
        if suggest and self.rewriter is not None:
            suggested = self.suggestions(history, drafts[0], account, when, min(suggest, 8), post_type.classify(drafts[0]["text"])["type"] == "launch",
                                         use_judge=plan["use"], share_history=share)
            js = suggested.pop("_judge", None)
            if js:
                judge_summaries.append(js)
                judge_wait += js["seconds"] or 0.0          # upper bound: these calls overlap with the scoring of the rewrites
        ctx = self._timing_context(history, when)
        table = [{"version": 1, "text": drafts[0]["text"], "likes_median": d["likes"]["q50"], "views_median": d["views_24h"]["q50"],
                  "likes_range": [d["likes"]["q10"], d["likes"]["q90"]], "views_range": [d["views_24h"]["q10"], d["views_24h"]["q90"]],
                  "type": (ty := post_type.classify(drafts[0]["text"])), "checklist": self.checklist(drafts[0], ty["type"], ctx)}]
        reports = [{"likes": d["likes"], "views_24h": d["views_24h"], "members": d.get("members") or [], "reads_as_launch": d.get("reads_as_launch"), "kind_reports": d.get("kind_reports")}]
        for i, dr in enumerate(drafts[1:]):
            c = alts[f"Version {i + 2}"]
            rep = c.pop("report")
            reports.append({"likes": rep["likes"], "views_24h": rep["views_24h"], "members": rep.get("members") or [], "reads_as_launch": rep.get("reads_as_launch"),
                            "kind_reports": rep.get("kind_reports")})
            table.append({"version": i + 2, "text": dr["text"], "likes_median": c["likes_q50"], "views_median": c["views_q50"],
                          "likes_range": [rep["likes"]["q10"], rep["likes"]["q90"]], "views_range": [rep["views_24h"]["q10"], rep["views_24h"]["q90"]],
                          "vs_version_1": {**{k: c[k] for k in ("p_better", "predicted_ratio", "status", "why", "members_agree")}, **self._opinions(c, 1, i + 2)},
                          "type": (ty := post_type.classify(dr["text"])), "checklist": self.checklist(dr, ty["type"], ctx)})
        for row, v, dr in zip(table, versions, drafts):
            kind = "video" if any(m["type"] == "video" for m in dr["media"]) else "image" if dr["media"] else None
            row["media"] = {**(v.get("media_info") or {}), "kind": kind} if kind else None
        comparison = self.compare_versions(reports, judged)
        judge_block = self._judge_block(plan, source, judge_summaries, len(drafts), judge_wait)
        judged_kinds = {p["kind"] for p in comparison["pairs"] if p.get("opinions")} | {r["kind"] for r in ((suggested or {}).get("better", []) + (suggested or {}).get("not_better", [])) if r.get("opinions")}
        pick = None if len(table) == 1 else {"version": comparison["winner"], "confidence": comparison["confidence"], "statement": comparison["statement"]}
        top = d["p_own_top_10pct"]["views"] if d["p_own_top_10pct"]["views"] is not None else d["p_own_top_10pct"]["likes"]
        is_launch = bool(req["launch"]) if req.get("launch") is not None else any(r["type"]["type"] == "launch" for r in table)
        gap_h = None if (asked_when is None or last_ms is None) else (when - last_ms) / 3_600_000
        plan = self.launch_plan(drafts, gap_h) if is_launch else None
        if plan:
            for row, met in zip(table, plan["met_by_version"]):
                row["plan_checks_met"] = met
        usual = d["own_median"]
        own = None
        if usual["likes"] is not None or usual["views"] is not None:
            own = {"likes": usual["likes"], "views": usual["views"], "posts_used": d["history_posts_used"],
                   "forecast_vs_usual": {"likes": [r["likes_median"] / usual["likes"] if usual["likes"] else None for r in table],
                                         "views": [r["views_median"] / usual["views"] if usual["views"] else None for r in table]},
                   "statement": "Your usual is the median of your most recent posts" + (f": {usual['likes']:,.0f} likes" if usual["likes"] is not None else "")
                                + (f", {usual['views']:,.0f} views" if usual["views"] is not None else "") + f" ({d['history_posts_used']} posts)."}
        benchmarks = {"own_usual": own,
                      "launch_for_size": self.size_benchmark(int(followers), usual["likes"]) if is_launch else None,
                      "launch_type": self.type_expectation("launch") if is_launch else None}
        tm = self.scorer.timings
        total = time.perf_counter() - clock
        enc = getattr(self.scorer, "encoder", None)
        embedding = self._embedding_block(enc.take_usage() if enc is not None and hasattr(enc, "take_usage") else None, getattr(self.scorer, "embed_counts", None))
        return {
            "report_version": REPORT_VERSION,
            "model_set": self.model_set,
            "embedding": embedding,
            "cost_usd": {"embedding": embedding["cost_usd"], "judge": judge_block["cost_usd"], "total": round(embedding["cost_usd"] + judge_block["cost_usd"], 6)},
            "generated_at": _iso(int(t0 * 1000)),
            "account": {"handle": handle or None, "followers": int(followers), "history_posts": history.height, "history_source": source,
                        "new_account": history.height < MIN_HISTORY},
            "when": _iso(when, "minutes") if asked_when else None,
            "post_type": table[0]["type"],
            "is_launch": is_launch,
            "type_expectation": self.type_expectation(table[0]["type"]["type"]),
            "odds": {"own_top_10pct": top, "reach_followers_1x": d["p_reach_1x"], "reach_followers_10x": d["p_reach_10x"], "reach_followers_100x": d["p_reach_100x"],
                     "lift_vs_own_median": d["lift_vs_own_median"], "own_median": d["own_median"]},
            "versions": table,
            "pick": pick,
            "comparison": comparison,
            "launch_plan": plan,
            "benchmarks": benchmarks,
            "changes": [c for c in out["changes"] if c["operator"] is not None],
            "suggested": suggested,
            "rules": [self._rule(g) for g in out["rules"]],
            "record": out["record"],
            "judge": judge_block,
            "method": self._method(out, is_launch, judge_block, judged_kinds),
            "timing_ms": {"history": round(1000 * t_hist), **{k: round(1000 * v) for k, v in tm.items()},
                          "judge_wait": round(1000 * judge_wait),
                          "other": max(0, round(1000 * (total - t_hist - sum(tm.values()) - judge_wait))), "total": round(1000 * total)},
            "seconds": round(time.time() - t0, 2),
        }

    FORECAST_VALIDATION = ("Version comparisons are checked on 2,852 real pairs of posts by one account about one topic: calls made at 60% confidence or more "
                           "were right 67% of the time, and 74% when the real gap was 3x or more.")

    def _method(self, out: dict, is_launch: bool, judge_block: dict, judged_kinds: set) -> dict:
        """`validation` states what was measured for the configuration that decided this report's comparisons: the
        forecasting model alone, or the forecasting model with the language model named in `judge` (then the forecasting
        model's own record moves to `forecast_model_validation`, which still applies to every pair the language model was
        not asked about and to the single edits under `changes`)."""
        jv = self._judge_validation(judged_kinds) if judge_block["used"] else None
        return {"outcome_compared": out["outcome_compared"], "thresholds": out["thresholds"],
                "validation": jv or self.FORECAST_VALIDATION,
                "forecast_model_validation": self.FORECAST_VALIDATION,
                "launch_validation": self._launch_validation() if is_launch else None,
                "judge_validation": jv,
                "comparisons_decided_by": "forecasting model and language model" if judge_block["used"] else "forecasting model"}

    @staticmethod
    def _rule(g: dict) -> dict:
        """A ticked "video" box carries no length, and X's check then reads as failed. Say what the rule is instead."""
        if g.get("gate") == "video_index" and g.get("status") == "fail" and g.get("duration_ms") is None:
            return {**g, "status": "warn", "detail": f"the video's length is not known: X's code admits a video to the out-of-network video index only if it is longer than "
                                                     f"{(g.get('min_ms') or 10_000) // 1000} seconds. Attach the file to check it."}
        return g

    def _launch_validation(self) -> str | None:
        if getattr(self, "launch_validation_text", None):
            return self.launch_validation_text
        m = self.launch_evidence.get("_model_check") or {}
        a, c = m.get("model_all"), m.get("model_confident_0.6_plus")
        if not a or not c:
            return None
        return (f"On {a['pairs']:,} held-out pairs of launch posts by the same account ({a['accounts']} accounts), the model picked the better one {100 * a['accuracy']:.1f}% of the time "
                f"({100 * a['lo']:.1f} to {100 * a['hi']:.1f}); at 60% confidence or more, {100 * c['accuracy']:.1f}% ({100 * c['lo']:.1f} to {100 * c['hi']:.1f}) on {c['pairs']} pairs.")


def load(checkpoints: list[str], scales_path: str | dict, posts: str | None = None, sid_codebook: str | None = None, encoder: str | None = None,
         device: str = "cpu", fast: bool = True, embed_batch: int = 16, type_correction: str | None = None, judge=None, judge_deadline: float = 40.0,
         judge_rule: str | None = None, selective_rule: str | None = None, selective_ensemble: str | None = None, fallback: Service | None = None,
         forecast_validation: str | None = None, launch_validation: str | None = None, model_set: str | None = None, embedder=None,
         kind_checkpoints: dict | None = None) -> Service:
    """type_correction: the post-type level correction for these checkpoints (research/tracks/posttype/type_correction.json
    for the three 46-column small models); it is fitted per model set and must not be reused for other checkpoints.
    encoder: None reads the encoder from the checkpoints (the name each was trained with is stored in it); a name must
    match it, and a mismatch is refused. embedder: an encoder object to use instead (tests pass the stub).
    embed_batch: texts per batch of a local encoder. It sorts by length, so small batches pad each post only to its
    neighbours; one batch of 256 pads a whole history to its longest post, which was most of a 25-second request.
    judge_rule, selective_rule (+ selective_ensemble): the rule files fitted for THIS model set; without selective_rule the
    shipped default is used, which belongs to the three bge-small models."""
    from xviral.serve import DraftScorer

    scorer = DraftScorer(checkpoints if len(checkpoints) > 1 else checkpoints[0], None, device=device, sid_codebook=sid_codebook, type_correction=type_correction,
                         encoder=embedder if embedder is not None else _encoder_for(checkpoints, encoder, device, embed_batch if fast else 256))
    # kind_checkpoints: {"launch": [checkpoints]}: members that decide that kind of comparison instead of `checkpoints`
    # (same encoder and codebook; they read the features and vectors the main scorer computed, so nothing more is embedded).
    for kind, cks in (kind_checkpoints or {}).items():
        ks = DraftScorer(cks if len(cks) > 1 else cks[0], None, device=device, sid_codebook=sid_codebook, encoder=scorer.encoder)
        if (ks.encoder_spec or {}).get("name") != (scorer.encoder_spec or {}).get("name"):
            raise ValueError(f"the {kind} comparison members were trained with {(ks.encoder_spec or {}).get('name')!r}, the forecast members with "
                             f"{(scorer.encoder_spec or {}).get('name')!r}; one bundle, one encoder")
        scorer.kind_scorers[kind] = ks
    raw = scales_path if isinstance(scales_path, dict) else json.load(open(scales_path))
    scales = {k: v for k, v in raw.items() if k in ("views", "likes")}
    selective = "auto"
    if selective_rule:
        from xviral.selective import SelectiveRule

        selective = SelectiveRule.load(selective_rule, selective_ensemble)
    rule = None
    if judge_rule:
        from xviral.judge import JudgeRule

        rule = JudgeRule.load(judge_rule)
    svc = Service(scorer, scales, posts=posts, fast=fast, judge=judge, judge_rule=rule, judge_deadline=judge_deadline, selective=selective, fallback=fallback,
                  forecast_validation=forecast_validation, model_set=model_set)
    svc.launch_validation_text = launch_validation
    return svc


def _encoder_for(checkpoints: list[str], name: str | None, device: str, batch: int):
    """The encoder the checkpoints were trained with. `name`, when given, must be that encoder."""
    import torch

    from xviral.embed import api as embed_api

    spec = embed_api.common_encoder([torch.load(c, map_location="cpu", weights_only=False)["table_meta"] for c in checkpoints])
    if name and name not in (spec["name"], spec["model"]):
        raise ValueError(f"XVIRAL_ENCODER is {name!r} but the checkpoints were trained with {spec['name']!r}; unset it or use the matching checkpoints")
    return embed_api.make_encoder(spec, device=device, batch=batch)


def load_bundle(path: str | Path, posts: str | None = None, judge=None, judge_deadline: float = 40.0, device: str = "cpu", embedder=None,
                fallback_embedder=None) -> Service:
    """One config for a whole model set: `bundle.json` (research/tracks/combine/REPORT.md) names the checkpoints, the
    semantic-ID codebook, the encoder, the confidence scales, the selective rule, the post-type correction, the judge rule
    and, optionally, a fallback model set with a local encoder. Paths in it are relative to the file."""
    path = Path(path)
    if path.is_dir():
        path = path / "bundle.json"
    cfg, root = json.loads(path.read_text()), path.parent
    rel = lambda v: None if not v else str(v if Path(v).is_absolute() else root / v)      # noqa: E731

    def one(c: dict, fb: Service | None, emb) -> Service:
        return load([rel(x) for x in c["checkpoints"]], c.get("scales") if isinstance(c.get("scales"), dict) else rel(c.get("scales")), posts=posts,
                    sid_codebook=rel(c.get("sid_codebook")), encoder=(c.get("encoder") or {}).get("name") if isinstance(c.get("encoder"), dict) else c.get("encoder"),
                    device=device, type_correction=rel(c.get("type_correction")), judge=judge, judge_deadline=judge_deadline, judge_rule=rel(c.get("judge_rule")),
                    selective_rule=rel(c.get("selective_rule")), selective_ensemble=c.get("selective_ensemble"), fallback=fb,
                    forecast_validation=(c.get("validation") or {}).get("statement"), launch_validation=(c.get("validation") or {}).get("launch_statement"),
                    model_set=c.get("name"), embedder=emb,
                    kind_checkpoints={k: [rel(x) for x in v["checkpoints"]] for k, v in (c.get("comparison_members") or {}).items()})

    fb = one(cfg["fallback"], None, fallback_embedder) if cfg.get("fallback") and (cfg["fallback"].get("checkpoints")) and all(Path(rel(x)).exists() for x in cfg["fallback"]["checkpoints"]) else None
    return one(cfg, fb, embedder)
