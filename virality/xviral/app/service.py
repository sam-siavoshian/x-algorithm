"""One request in, one report out: an account, its past posts and one or more versions of a draft.

Everything in the report is one of four things, and the report says which:
  forecast   what the model predicts for each version (ranges and odds)
  verdict    which version is predicted to do better, with a probability validated on real pairs of posts
  rules      checks taken from X's published ranking code
  checklist  attributes with an effect measured in controlled pairs of real posts; each line carries its numbers
No sentence is generated by a language model.
"""

from __future__ import annotations

import json
import time
from datetime import datetime, timezone
from pathlib import Path

import polars as pl

from xviral import advise
from xviral.schema import conform
from xviral.text import post_type
from xviral.util.core import stable_hash64

VIDEO = {**advise.PHOTO, "type": "video"}
MIN_HISTORY = 10          # fewer past posts than this and the account is treated as new: wider ranges, no own-record facts


def _ms(v) -> int | None:
    if v is None or v == "":
        return None
    if isinstance(v, (int, float)):
        return int(v if v > 1e11 else v * 1000)
    d = datetime.fromisoformat(str(v).replace("Z", "+00:00"))
    return int((d if d.tzinfo else d.replace(tzinfo=timezone.utc)).timestamp() * 1000)


def history_frame(handle: str, followers: int | None, past: list[dict], now_ms: int) -> pl.DataFrame:
    """Past posts typed in or uploaded by the user, as rows of the post schema."""
    rows = []
    for i, p in enumerate(past):
        ms = _ms(p.get("posted_at"))
        if ms is None or not (p.get("text") or "").strip():
            continue
        media = [dict(VIDEO)] if p.get("video") else [dict(advise.PHOTO)] if p.get("image") else []
        rows.append({"post_id": -stable_hash64("past", handle, ms, i), "author_id": -1, "author_handle": handle, "created_at_ms": ms, "created_at_src_ms": ms,
                     "snapshot_at_ms": now_ms, "snapshot_kind": "exact", "text": p["text"], "kind": "original", "is_reply": False, "media": media, "urls": [],
                     "likes": p.get("likes"), "replies": p.get("replies"), "reposts": p.get("reposts"), "views": p.get("views"),
                     "views_state": "count" if p.get("views") is not None else "absent", "author_followers": followers, "source": "analytics", "synthetic_id": True})
    empty = conform(pl.DataFrame()).clear()
    if not rows:
        return empty
    return conform(pl.DataFrame(rows, infer_schema_length=None, schema_overrides={"media": empty.schema["media"], "urls": empty.schema["urls"]})).sort("created_at_ms")


class Service:
    def __init__(self, scorer, scales: dict, posts: str | Path | None = None, evidence: dict | None = None, max_history: int = 300):
        self.scorer, self.posts, self.max_history = scorer, posts, max_history
        self.advisor = advise.Advisor(scorer, scales, evidence=evidence)
        self.evidence = self.advisor.evidence
        lp = Path(advise.EVIDENCE_PATH).with_name("launch_evidence.json")
        self.launch_evidence = json.loads(lp.read_text()) if lp.exists() else {}

    # --- inputs --------------------------------------------------------------------------------------------

    def _history(self, handle: str, followers: int | None, past: list[dict], now_ms: int) -> tuple[pl.DataFrame, str, int | None]:
        if past:
            return history_frame(handle, followers, past, now_ms), "posts you supplied", followers
        if self.posts and handle:
            h = pl.scan_parquet(self.posts).filter(pl.col("author_handle").str.to_lowercase() == handle.lower()).collect().sort("created_at_ms").tail(self.max_history)
            if h.height:
                known = h["author_followers"].drop_nulls()
                return h, "our corpus of public posts", followers or (int(known[-1]) if known.len() else None)
        return conform(pl.DataFrame()).clear(), "none", followers

    @staticmethod
    def _draft(v: dict) -> dict:
        return {"text": (v.get("text") or "").strip(), "media": [dict(VIDEO)] if v.get("video") else [dict(advise.PHOTO)] if v.get("image") else []}

    # --- the measured checklist -----------------------------------------------------------------------------

    def _generic_checklist(self, draft: dict) -> list[dict]:
        ev, text = self.evidence, draft["text"]
        items = []

        def add(key: str, ok: bool, yes: str, no: str, evidence_key: str):
            e = ev.get(evidence_key) or {}
            if not e.get("supported"):
                return
            items.append({"key": key, "ok": bool(ok), "text": yes if ok else no, "grade": None,
                          "measured": f"In {e['pairs']:,} pairs of posts by the same account on the same topic, the version with this did better {100 * e['win_rate']:.0f}% of the time "
                                      f"({100 * e['lo']:.0f} to {100 * e['hi']:.0f}%)."})
        lines = [ln for ln in text.split("\n") if ln.strip()]
        add("media", bool(draft["media"]), "Has an image or video.", "No image or video attached.", "media")
        add("lines", len(lines) >= 3, "Broken into three or more lines.", "One block of text; fewer than three lines.", "lines")
        if "http" in text:
            add("link", "http" not in (lines[0] if lines else ""), "The link is not in the first line.", "The link is in the first line.", "link_not_first")
        return items

    def _launch_checklist(self, draft: dict) -> list[dict]:
        """For launch posts: the traits that separate an account's stronger launch posts from its weaker ones."""
        ev, tr = self.launch_evidence, post_type.traits(draft["text"], draft["media"])
        items = []

        def add(key: str, ok: bool, yes: str, no: str, evidence_key: str, note: str = ""):
            e = ev.get(evidence_key) or {}
            if not e.get("grade"):
                return
            ratio = (e.get("likes_ratio") or {}).get("ratio")
            items.append({"key": key, "ok": bool(ok), "text": yes if ok else no, "grade": e["grade"],
                          "measured": f"Among launch posts by the same account, the one with this did better {100 * e['win_rate']:.0f}% of the time ({100 * e['lo']:.0f} to {100 * e['hi']:.0f}%), "
                                      f"{e['pairs']:,} pairs from {e['accounts']} accounts" + (f"; about {ratio:.1f}x the likes." if ratio else ".") + (" " + note if note else "")})
        add("names_product", tr["names_product_first_line"], "The first line names the product.", "The first line does not name the product.", "names_product_first_line")
        add("lines", tr["lines3"], "Laid out on three or more lines.", "Fewer than three lines.", "lines3")
        if tr["video"]:
            add("video", True, "Has a video or GIF.", "", "video_vs_none")
        elif tr["image"]:
            add("video", False, "", "Has an image, not a video or GIF.", "video_vs_image", "A still image is not established as better than no media for a launch post.")
        else:
            add("video", False, "", "No video or GIF.", "video_vs_none", "A still image is not established as better than no media for a launch post.")
        add("announcement_first", not tr["open_problem"], "Opens with the announcement.", "Opens with a problem statement or a question, not the announcement.", "announcement_not_problem_first")
        add("no_link", not tr["ext_link"], "No external link in the post.", "Has an external link in the post.", "no_link_in_post",
            "Whether a link in a reply recovers the clicks could not be measured.")
        add("number", tr["open_number"], "The first line contains a number.", "No number in the first line.", "open_number", "The weakest of the findings.")
        order = {"A": 0, "A-": 1, "B": 2, "B-": 3, "C": 4}
        return sorted(items, key=lambda i: (i["ok"], order.get(i["grade"], 9)))

    def checklist(self, draft: dict, kind: str) -> list[dict]:
        return self._launch_checklist(draft) if kind == "launch" and self.launch_evidence else self._generic_checklist(draft)

    def type_expectation(self, kind: str) -> dict | None:
        """How posts of this kind do against the account's own usual, for company and founder accounts."""
        e = ((self.launch_evidence.get("_types") or {}).get("company_and_founder") or {}).get(kind, {}).get("likes")
        if not e or e["posts"] < 50:
            return None
        return {"likes_vs_usual": e["geo_mean_ratio"], "lo": e["geo_mean_lo"], "hi": e["geo_mean_hi"], "beat_usual": e["beat_own_median"], "own_top_10pct": e.get("top10_of_own"),
                "posts": e["posts"], "accounts": e["accounts"],
                "statement": f"{post_type.LABELS[kind]} posts by company and founder accounts got {e['geo_mean_ratio']:.1f}x the account's usual likes ({e['geo_mean_lo']:.1f} to {e['geo_mean_hi']:.1f}); "
                             f"{100 * e['beat_own_median']:.0f}% beat the account's usual. Measured on {e['posts']:,} posts from {e['accounts']} accounts. "
                             "The forecast above does not yet include this lift."}

    # --- the report ------------------------------------------------------------------------------------------

    def analyze(self, req: dict) -> dict:
        t0 = time.time()
        now_ms = int(t0 * 1000)
        handle = (req.get("handle") or "").lstrip("@").strip()
        versions = [v for v in (req.get("versions") or []) if (v.get("text") or "").strip()]
        if not versions:
            raise ValueError("at least one version of the draft is required")
        history, source, followers = self._history(handle, req.get("followers"), req.get("past_posts") or [], now_ms)
        if followers is None:
            raise ValueError("follower count is required for an account we have no posts for")
        when = _ms(req.get("when")) or (max(now_ms, int(history["created_at_ms"].max()) + 3_600_000) if history.height else now_ms)
        account = {"handle": handle or "draft", "followers": int(followers)}
        if not history.height:
            account["author_id"] = -1
        drafts = [self._draft(v) for v in versions]
        out = self.advisor.advise(history, drafts[0], account, when, alternatives=[{**d, "label": f"Version {i + 2}"} for i, d in enumerate(drafts[1:])])
        alts = {c["change"]: c for c in out["changes"] if c["operator"] is None}

        def forecast(likes_q50, views_q50):
            return {"likes_median": likes_q50, "views_median": views_q50}
        table = [{"version": 1, "text": drafts[0]["text"], **forecast(out["draft"]["likes"]["q50"], out["draft"]["views_24h"]["q50"]),
                  "likes_range": [out["draft"]["likes"]["q10"], out["draft"]["likes"]["q90"]], "views_range": [out["draft"]["views_24h"]["q10"], out["draft"]["views_24h"]["q90"]],
                  "type": (ty := post_type.classify(drafts[0]["text"])), "checklist": self.checklist(drafts[0], ty["type"])}]
        for i, d in enumerate(drafts[1:]):
            c = alts[f"Version {i + 2}"]
            table.append({"version": i + 2, "text": d["text"], **forecast(c["likes_q50"], c["views_q50"]), "vs_version_1": {k: c[k] for k in ("p_better", "predicted_ratio", "status", "why", "members_agree")},
                          "type": (ty := post_type.classify(d["text"])), "checklist": self.checklist(d, ty["type"])})
        # The pick: a version other than the first is named only when it clears the same gates as any recommendation.
        better = [r for r in table[1:] if r["vs_version_1"]["status"].startswith("recommended")]
        worse_all = len(table) > 1 and all(r["vs_version_1"]["status"] == "predicted_worse" for r in table[1:])
        if better:
            best = max(better, key=lambda r: r["vs_version_1"]["p_better"])
            pick = {"version": best["version"], "confidence": best["vs_version_1"]["p_better"],
                    "statement": f"Version {best['version']} is predicted to do better than version 1 ({100 * best['vs_version_1']['p_better']:.0f}% likely, about {best['vs_version_1']['predicted_ratio']:.1f}x the likes)."}
        elif worse_all:
            p = min(1 - r["vs_version_1"]["p_better"] for r in table[1:])
            pick = {"version": 1, "confidence": p, "statement": f"Version 1 is predicted to do better than the other version{'s' if len(table) > 2 else ''} ({100 * p:.0f}% likely)."}
        elif len(table) > 1:
            pick = {"version": None, "confidence": None, "statement": "The versions are too close to call. Post whichever you prefer; we cannot tell them apart with confidence."}
        else:
            pick = None
        d = out["draft"]
        top = d["p_own_top_10pct"]["views"] if d["p_own_top_10pct"]["views"] is not None else d["p_own_top_10pct"]["likes"]
        return {
            "account": {"handle": handle or None, "followers": int(followers), "history_posts": history.height, "history_source": source,
                        "new_account": history.height < MIN_HISTORY},
            "post_type": table[0]["type"],
            "type_expectation": self.type_expectation(table[0]["type"]["type"]),
            "odds": {"own_top_10pct": top, "reach_followers_1x": d["p_reach_1x"], "reach_followers_10x": d["p_reach_10x"], "reach_followers_100x": d["p_reach_100x"],
                     "lift_vs_own_median": d["lift_vs_own_median"], "own_median": d["own_median"]},
            "versions": table,
            "pick": pick,
            "changes": [c for c in out["changes"] if c["operator"] is not None],
            "rules": out["rules"],
            "record": out["record"],
            "method": {"outcome_compared": out["outcome_compared"], "thresholds": out["thresholds"],
                       "validation": "Version comparisons are checked on 2,852 real pairs of posts by one account about one topic: calls made at 60% confidence or more "
                                     "were right 67% of the time, and 74% when the real gap was 3x or more."},
            "seconds": round(time.time() - t0, 2),
        }


def load(checkpoints: list[str], scales_path: str, posts: str | None = None, sid_codebook: str | None = None, encoder: str = "BAAI/bge-small-en-v1.5",
         device: str = "cpu") -> Service:
    from xviral.embed.text_small import SentenceEmbedder
    from xviral.serve import DraftScorer

    enc = SentenceEmbedder(encoder, device=device)
    scorer = DraftScorer(checkpoints if len(checkpoints) > 1 else checkpoints[0], lambda texts: enc.encode(texts), device=device, sid_codebook=sid_codebook)
    scales = {k: v for k, v in json.load(open(scales_path)).items() if k in ("views", "likes")}
    return Service(scorer, scales, posts=posts)
