"""One request in, one report out: an account, its past posts and one or more versions of a draft.

Everything in the report is one of these things, and the report says which:
  forecast    what the model predicts for each version (ranges and odds)
  verdict     which version is predicted to do better, with a probability validated on real pairs of posts
  rules       checks taken from X's published ranking code
  checklist   attributes with an effect measured in controlled pairs of real posts; each line carries its numbers
  plan        for a launch: the traits measured on launch posts (xviral/data/launch_evidence.json), with grades
  benchmarks  the forecast next to the account's own usual and to what launch posts did for accounts of its size
No sentence is generated by a language model. When a judge is configured (XVIRAL_JUDGE_MODEL), a language model gives a
second opinion on which version does better; the report's `judge` block names the provider and the model, says what was
sent, and the method note states the accuracy measured for that configuration (research/tracks/judge_product/REPORT.md).

Speed: the scorer runs in its fast mode (serve.DraftScorer.fast), account histories and their own-record facts are kept
in a small cache, and the scorer caches text embeddings. tests/test_app.py holds the equality test against the original
path; research/tracks/product/REPORT.md has the timings.
"""

